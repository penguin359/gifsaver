"""Convert a GIF or WAV file into a C header with the data as a byte array.

Usage:
    embed2c.py input.{gif,wav} [output.h]

The file type is detected from its magic bytes. By default the output is
default_gif.h (symbol gifsaver_default_gif) or default_wav.h (symbol
gifsaver_default_wav), which is what gifsaver.c includes when
GIFSAVER_EMBED_GIF / GIFSAVER_EMBED_WAV are enabled in config.h.
"""

import os
import sys


def detect_kind(data: bytes) -> str:
    if data[:6] in (b"GIF87a", b"GIF89a"):
        return "gif"
    if data[:4] == b"RIFF" and data[8:12] == b"WAVE":
        return "wav"
    raise SystemExit("error: input is neither a GIF nor a RIFF/WAVE file")


def main() -> None:
    if len(sys.argv) not in (2, 3):
        raise SystemExit(__doc__.strip())

    src = sys.argv[1]
    with open(src, "rb") as f:
        data = f.read()
    kind = detect_kind(data)

    out = sys.argv[2] if len(sys.argv) == 3 else f"default_{kind}.h"
    symbol = f"gifsaver_default_{kind}"
    guard = f"GIFSAVER_DEFAULT_{kind.upper()}_H"

    with open(out, "w") as f:
        f.write(f"/* Generated by embed2c.py from {os.path.basename(src)}"
                f" ({len(data)} bytes). Do not edit. */\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n\n")
        f.write(f"static const unsigned char {symbol}[] = {{\n")
        for i in range(0, len(data), 12):
            chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
            f.write(f"    {chunk},\n")
        f.write("};\n\n")
        f.write(f"#endif /* {guard} */\n")

    print(f"wrote {out}: {symbol}[{len(data)}] from {src}")


if __name__ == "__main__":
    main()
